def _write_wav_mono(path: Path, samples: list[float], sample_rate: int = 44100) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "w") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(sample_rate)
        for value in samples:
            clamped = max(-1.0, min(1.0, value))
            handle.writeframes(struct.pack("<h", int(clamped * 32767)))


def _soft_clip(value: float, drive: float = 2.2) -> float:
    return math.tanh(value * drive) / math.tanh(drive)


def _synth_808(sample_rate: int = 44100, duration: float = 0.62) -> list[float]:
    total = int(sample_rate * duration)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        progress = min(1.0, t / duration)
        freq = 62 * (1.0 - 0.62 * progress) + 28
        body = math.sin(2 * math.pi * freq * t)
        click = math.sin(2 * math.pi * 180 * t) * math.exp(-90 * t) * 0.35
        env = math.exp(-2.4 * t) * (1.0 - progress * 0.12)
        out.append(_soft_clip((body * 0.95 + click) * env, drive=2.8))
    return out


def _synth_808_bass(sample_rate: int = 44100, duration: float = 0.42) -> list[float]:
    """Short, punchy 808 hit — same tonal family as _synth_808 (sine body +
    click, tanh saturation) but a fraction of the duration and a faster
    envelope, so it reads as a retriggered punch instead of a sustained
    glide-y sub. First-draft constants, meant to be ear-tuned once a genre
    actually opts into GenreProfile.bass808_enabled.

    duration was 0.22s / decay -14 until 2026-08: below
    library_quality._MIN_808_SECONDS (0.35s) and, even once lengthened to
    clear that floor alone, still decayed too fast for
    audio_features._MAX_808_TRANSIENT_BODY_RATIO (its 120-800ms "body"
    window was already near-silent). Both were failing every time this
    last-resort fallback was actually needed, silently dropping the whole
    808_bass lane from export instead of ever being used. duration=0.42/
    decay=6 clears both checks with room to spare while staying
    noticeably punchier/shorter than _synth_808's sustained -2.4 decay."""
    total = int(sample_rate * duration)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        progress = min(1.0, t / duration)
        freq = 58 * (1.0 - 0.35 * progress) + 40  # short/minimal glide, stays near-fixed pitch
        body = math.sin(2 * math.pi * freq * t)
        click = math.sin(2 * math.pi * 200 * t) * math.exp(-140 * t) * 0.5
        env = math.exp(-6 * t)  # faster decay than _synth_808's -2.4 — punchier tail
        out.append(_soft_clip((body * 0.9 + click) * env, drive=3.0))
    return out


def _synth_hat(sample_rate: int = 44100, duration: float = 0.055) -> list[float]:
    import random

    random.seed(808)
    total = int(sample_rate * duration)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        noise = random.uniform(-1, 1)
        tone = math.sin(2 * math.pi * 9200 * t) * 0.15
        env = math.exp(-70 * t)
        out.append(_soft_clip((noise * 0.75 + tone) * env * 0.55, drive=1.8))
    return out


def _synth_kick(sample_rate: int = 44100, duration: float = 0.18) -> list[float]:
    total = int(sample_rate * duration)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        click = math.sin(2 * math.pi * 120 * t) * math.exp(-55 * t)
        body = math.sin(2 * math.pi * 55 * t) * math.exp(-18 * t)
        out.append(_soft_clip((click * 0.55 + body * 0.85) * 0.9, drive=2.4))
    return out


def _synth_snare(sample_rate: int = 44100, duration: float = 0.22) -> list[float]:
    import random

    random.seed(909)
    total = int(sample_rate * duration)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        noise = random.uniform(-1, 1)
        tone = math.sin(2 * math.pi * 180 * t) * math.exp(-35 * t)
        env = math.exp(-16 * t)
        out.append(_soft_clip((noise * 0.7 + tone * 0.35) * env * 0.75, drive=2.0))
    return out


def _synth_clap(sample_rate: int = 44100, duration: float = 0.16) -> list[float]:
    import random

    random.seed(707)
    total = int(sample_rate * duration)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        burst = random.uniform(-1, 1) if (i % 120) < 40 else random.uniform(-0.4, 0.4)
        env = math.exp(-28 * t)
        out.append(_soft_clip(burst * env * 0.55, drive=1.7))
    return out


def _synth_melody_pluck(sample_rate: int = 44100, duration: float = 0.45) -> list[float]:
    total = int(sample_rate * duration)
    freqs = (440.0, 660.0, 880.0)
    out: list[float] = []
    for i in range(total):
        t = i / sample_rate
        env = math.exp(-7.5 * t)
        value = sum(math.sin(2 * math.pi * freq * t) * weight for freq, weight in zip(freqs, (0.55, 0.3, 0.15)))
        out.append(_soft_clip(value * env * 0.42, drive=1.6))
    return out


def _write_manifest(source: str, paths: dict[str, Path]) -> None:
    _manifest_file().write_text(
        json.dumps(
            {"source": source, "bundle_version": BUNDLE_VERSION, "files": {k: str(v) for k, v in paths.items()}},
            indent=2,
        ),
        encoding="utf-8",
    )


def _existing_paths() -> dict[str, Path] | None:
    paths = {
        track: (_starter_dir() / filename).resolve()
        for track, filename in TRACK_STARTER_FILES.items()
        if (_starter_dir() / filename).is_file()
    }
    if len(paths) == len(TRACK_STARTER_FILES):
        return paths
    return None


def _seed_from_bundle() -> dict[str, Path] | None:
    """Copy shipped starter wavs into the runtime folder (first run / after install)."""
    from build_bundled_sounds import ensure_bundled_sounds, pick_bundled_for_track

    ensure_bundled_sounds()
    bundled = starter_bundle_dir()
    runtime = _starter_dir()
    manifest = _manifest_file()
    if manifest.is_file():
        try:
            # A legacy CC0-upgrade install keeps its own files: return them
            # rather than seeding bundled audio over the top.
            if json.loads(manifest.read_text(encoding="utf-8")).get("source") == LEGACY_STARTER_SOURCE:
                return _existing_paths()
        except (OSError, json.JSONDecodeError):
            pass

    copied = False
    for filename in TRACK_STARTER_FILES.values():
        src = bundled / filename
        dest = runtime / filename
        if src.is_file() and not dest.is_file():
            shutil.copy2(src, dest)
            copied = True

    pool = bundled_sounds_dir()
    if pool.is_dir():
        for track, filename in TRACK_STARTER_FILES.items():
            dest = runtime / filename
            if dest.is_file():
                continue
            picked = pick_bundled_for_track(track)
            if picked and picked.is_file():
                shutil.copy2(picked, dest)
                copied = True

    if bundled.joinpath("BUNDLED.json").is_file() and not (runtime / "BUNDLED.json").is_file():
        shutil.copy2(bundled / "BUNDLED.json", runtime / "BUNDLED.json")

    if copied:
        paths = _existing_paths()
        if paths:
            logging.info("Installed bundled PLG starter sounds to %s", runtime)
            _write_manifest("plg_bundled", paths)
            return paths
    return _existing_paths()


def _ensure_synthetic_starter() -> dict[str, Path]:
    from build_bundled_sounds import ensure_bundled_sounds, pick_bundled_for_track

    ensure_bundled_sounds()
    runtime = _starter_dir()
    generators = {
        "kick": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["kick"], _synth_kick()),
        "snare": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["snare"], _synth_snare()),
        "clap": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["clap"], _synth_clap()),
        "hi_hats": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["hi_hats"], _synth_hat()),
        "sub_808": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["sub_808"], _synth_808()),
        "808_bass": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["808_bass"], _synth_808_bass()),
        "melody_lead": lambda: _write_wav_mono(runtime / TRACK_STARTER_FILES["melody_lead"], _synth_melody_pluck()),
    }
    paths: dict[str, Path] = {}
    for track, filename in TRACK_STARTER_FILES.items():
        path = runtime / filename
        if not path.is_file():
            picked = pick_bundled_for_track(track)
            if picked and picked.is_file():
                shutil.copy2(picked, path)
            else:
                logging.info("Creating PLG synth starter: %s", path.name)
                generators[track]()
        paths[track] = path.resolve()
    _write_manifest("plg_synth", paths)
    return paths


def _score_name(name: str, keywords: tuple[str, ...]) -> tuple[int, int]:
    lower = name.lower()
    return sum(10 for keyword in keywords if keyword in lower), -len(lower)


def _pick_wav(root: Path, keywords: tuple[str, ...]) -> Path | None:
    files = list(root.rglob("*.wav"))
    if not files:
        return None
    return max(files, key=lambda path: _score_name(path.name, keywords))


def _legacy_starter_paths() -> dict[str, Path] | None:
    """Starter files an old CC0-upgrade install left behind, if any.

    Those bytes are the user's current sound. We identify them so the state is
    visible, and then hand them straight back untouched -- nothing here
    rewrites, regenerates or deletes them. Restoring first-party audio on such
    an install would change what the producer already hears, so it stays an
    explicit, separate decision rather than a silent migration.
    """
    manifest = _manifest_file()
    if not manifest.is_file():
        return None
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, ValueError):
        return None
    if data.get("source") != LEGACY_STARTER_SOURCE:
        return None

    paths = _existing_paths()
    if paths:
        logging.info(
            "Starter kit came from the retired CC0 upgrade path (%s). Leaving those "
            "files untouched; the installer that produced them no longer exists.",
            _starter_dir(),
        )
    return paths


def ensure_starter_kit() -> dict[str, Path]:
    """Bundled starter (default) → synth fallback.

    Legacy CC0-upgrade installs keep whatever they already have.
    """
    legacy = _legacy_starter_paths()
    if legacy:
        return legacy

    bundled = _seed_from_bundle()
    if bundled:
        return bundled

    return _ensure_synthetic_starter()


def _collect_audio_in_folders(library_root: Path, folders: tuple[str, ...]) -> list[Path]:
    paths: list[Path] = []
    for folder in folders:
        base = library_root / folder
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if path.suffix.lower() in AUDIO_EXTENSIONS:
                paths.append(path.resolve())
    return paths


def _wrong_type_for_lane(track: str, path: Path, root: Path) -> bool:
    """True when the file's own name/path says it belongs to ANOTHER lane.

    The matcher hard-rejects that (score -50000: an 808 or a kick can never be a
    snare); the "first file in the lane's folder" fallback below used to skip the
    matcher entirely, so a kit with no snare files handed its 808 to the snare
    and its kick to the clap. Same rule, same owner (``score_candidate``).
    """
    from sample_match import TRACK_PROFILES

    if track not in TRACK_PROFILES:
        return False
    try:
        rel = relative_in_library(path, Path(root)).as_posix()
    except (OSError, ValueError):
        rel = f"{Path(path).parent.name}/{Path(path).name}"
    from sample_match import _audio_vouches

    if score_candidate(
        rel, track, prompt_tokens=set(), style_tokens=set(), prompt_raw="", audio_vouches=_audio_vouches(Path(path), track)
    ) <= -50_000:
        return True
    # An untyped file (no lane word in its name) is also the wrong file when its
    # SOUND is clearly another drum: sound_type, via the shared gate.
    from sample_match import track_candidate_rejection_reasons

    return "sound_conflicts_with_track" in track_candidate_rejection_reasons(path, track, library_root=root)


def resolve_track_samples(
    catalog: dict[str, Any] | None,
    *,
    library_root: Path | None = None,
    prompt: str = "",
    style: str = "",
    melody_energy: dict[str, Any] | None = None,
) -> dict[str, Path]:
    # Variant B (2026-10, sound_policy): a lane the user has no file for is left out of the .flp, with its
    # notes; our starter sounds fill it only when PLG_SUBSTITUTE_SOUNDS is on.
    starter = ensure_starter_kit() if substitutes_allowed() else {}
    root = Path(library_root or (catalog or {}).get("root") or DEFAULT_LIBRARY_DIR)
    if isinstance(root, str):
        root = Path(root)

    from kit_variety import pick_with_variety
    from generation_variety import active_context, active_seed, disliked_sample_names

    ctx = active_context() or {}
    blocked_names = disliked_sample_names() | {str(n) for n in (ctx.get("forbidden_samples") or [])}

    chosen: dict[str, Path] = {}
    user_audio = int((catalog or {}).get("audio_total", 0) or 0) > 0
    if catalog and user_audio:
        kit = pick_with_variety(
            catalog,
            root,
            prompt=prompt,
            style=style,
            variety_seed=active_seed(),
            blocked_names=blocked_names,
            melody_energy=melody_energy,
        )
        for track, (path, score) in kit.items():
            chosen[track] = path
            logging.info("Matched %s <- %s (score %s)", track, path.name, score)

    for track in KIT_TRACK_ORDER:
        if track in chosen:
            continue
        fallback = _collect_audio_in_folders(root, TRACK_SEARCH_FOLDERS[track])
        for path in fallback:
            if path in chosen.values() or _wrong_type_for_lane(track, path, root):
                continue
            chosen[track] = path
            break
        if track not in chosen and track in starter:
            chosen[track] = starter[track]

    used = {str(p.resolve()) for p in chosen.values()}
    if catalog:
        # Same variety treatment as the main kit: rotate the top band per
        # generation and avoid the last kits' rim — the layer was the one
        # channel that repeated the exact same file every beat.
        import random as _random

        from kit_variety import last_kit_paths

        layer_path, layer_score = pick_best_for_track(
            catalog,
            "snare_layer",
            root,
            prompt=prompt,
            style=style,
            exclude=used | last_kit_paths(recent=3),
            variety_rng=_random.Random((active_seed() or 0) + 7),
            melody_energy=melody_energy,
        )
        if layer_path is None:
            layer_path, layer_score = pick_best_for_track(
                catalog,
                "snare_layer",
                root,
                prompt=prompt,
                style=style,
                exclude=used,
                variety_rng=_random.Random((active_seed() or 0) + 7),
                melody_energy=melody_energy,
            )
    else:
        layer_path, layer_score = None, 0
    if layer_path is not None:
        chosen["snare_layer"] = layer_path
        logging.info("Matched snare_layer <- %s (score %s)", layer_path.name, layer_score)
    elif "snare" in chosen:
        chosen["snare_layer"] = chosen["snare"]

    return chosen


